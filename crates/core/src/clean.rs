struct Compiled {
    rule: CleanRule,
    regex: Regex,
    max_chars: usize,
}

fn expanded(regex: &str) -> String {
    let with_domain = regex.replace("DOMAIN", DOMAIN);
    with_domain.replace(r"\b", r"(?-u:\b)")
}

fn compiled() -> &'static [Compiled] {
    static COMPILED: OnceLock<Vec<Compiled>> = OnceLock::new();
    COMPILED.get_or_init(|| {
        RULES
            .iter()
            .flat_map(|spec| match spec.matcher {
                Matcher::Patterns(patterns) => patterns
                    .iter()
                    .map(|pattern| Compiled {
                        rule: spec.rule,
                        regex: RegexBuilder::new(&expanded(pattern.regex))
                            .case_insensitive(true)
                            .build()
                            .expect("a cleanup pattern compiles"),
                        max_chars: pattern.max_chars,
                    })
                    .collect(),
                Matcher::RepeatedHeading | Matcher::ChapterTitles => Vec::new(),
            })
            .collect()
    })
}

