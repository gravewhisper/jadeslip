#[derive(Debug, PartialEq, Eq)]
pub(crate) enum Change {
    Remove { rule: CleanRule, para: usize },
    Retitle(Retitle),
}

impl Change {
    pub(crate) fn rule(&self) -> CleanRule {
        match self {
            Change::Remove { rule, .. } => *rule,
            Change::Retitle(_) => CleanRule::Titles,
        }
    }

    pub(crate) fn para(&self) -> usize {
        match self {
            Change::Remove { para, .. } => *para,
            Change::Retitle(retitle) => retitle.heading,
        }
    }
}

fn fold_char(ch: char) -> char {
    match ch {
        'ᴀ' => 'a',
        'ʙ' => 'b',
        'ᴄ' => 'c',
        'ᴅ' => 'd',
        'ᴇ' => 'e',
        'ꜰ' => 'f',
        'ɢ' => 'g',
        'ʜ' => 'h',
        'ɪ' => 'i',
        'ᴊ' => 'j',
        'ᴋ' => 'k',
        'ʟ' => 'l',
        'ᴍ' => 'm',
        'ɴ' => 'n',
        'ᴏ' => 'o',
        'ᴘ' => 'p',
        'ǫ' => 'q',
        'ʀ' => 'r',
        'ꜱ' => 's',
        'ᴛ' => 't',
        'ᴜ' => 'u',
        'ᴠ' => 'v',
        'ᴡ' => 'w',
        'ʏ' => 'y',
        'ᴢ' => 'z',
        '\u{FF01}'..='\u{FF5E}' => char::from_u32(ch as u32 - 0xFEE0).unwrap_or(ch),
        other => other,
    }
}

fn normalize(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut gap = false;
    for ch in text.chars().map(fold_char) {
        if ch.is_whitespace() {
            gap = !out.is_empty();
        } else {
            if gap {
                out.push(' ');
                gap = false;
            }
            out.push(ch);
        }
    }
    out
}

enum Tok {
    Content(Span),
    Br(Span),
    Hard,
}

#[derive(Clone, Copy)]
enum Edge {
    Block,
    Br(Span),
    Hard,
}

enum Item {
    Line(Span),
    Sep(Edge),
}

fn is_heading(name: &str) -> bool {
    matches!(
        local_name(name).to_ascii_lowercase().as_str(),
        "h1" | "h2" | "h3" | "h4" | "h5" | "h6"
    )
}

fn tokens(events: &[Event<'_>]) -> Vec<Tok> {
    let mut toks = Vec::new();
    for event in events {
        match event {
            Event::Text { raw, span } | Event::CData { raw, span } => {
                let trimmed = raw.trim_start_matches(|ch: char| ch.is_ascii_whitespace());
                if trimmed.is_empty() {
                    continue;
                }
                let start = span.start + (raw.len() - trimmed.len()) as u32;
                let end = start
                    + trimmed
                        .trim_end_matches(|ch: char| ch.is_ascii_whitespace())
                        .len() as u32;
                toks.push(Tok::Content(Span { start, end }));
            }
            Event::Other { .. } => {}
            Event::Open { name, span, .. } | Event::Close { name, span } => {
                let local = local_name(name);
                if local.eq_ignore_ascii_case("br") {
                    toks.push(Tok::Br(*span));
                } else if matches!(
                    class_of(local),
                    ElementClass::Block | ElementClass::Container
                ) {
                    toks.push(Tok::Hard);
                } else {
                    toks.push(Tok::Content(*span));
                }
            }
        }
    }
    toks
}

fn items(toks: Vec<Tok>) -> Vec<Item> {
    let mut items: Vec<Item> = Vec::new();
    for tok in toks {
        match (tok, items.last_mut()) {
            (Tok::Content(span), Some(Item::Line(line))) => line.end = span.end,
            (Tok::Content(span), _) => items.push(Item::Line(span)),
            (Tok::Br(span), Some(Item::Sep(Edge::Br(run)))) => run.end = span.end,
            (Tok::Br(span), _) => items.push(Item::Sep(Edge::Br(span))),
            (Tok::Hard, _) => items.push(Item::Sep(Edge::Hard)),
        }
    }
    items
}

fn balanced(events: &[Event<'_>], cut: Span) -> bool {
    let mut open: Vec<&str> = Vec::new();
    for event in events {
        let nests = match event {
            Event::Open {
                name,
                span,
                self_closed: false,
                ..
            } if within(*span, cut) => {
                open.push(name);
                true
            }
            Event::Close { name, span } if within(*span, cut) => open.pop() == Some(*name),
            _ => true,
        };
        if !nests {
            return false;
        }
    }
    open.is_empty()
}

fn within(span: Span, cut: Span) -> bool {
    span.start >= cut.start && span.start < cut.end
}

fn line_cut(line: Span, left: Edge, right: Edge, block: Span, kind: BlockKind) -> Option<Span> {
    match (left, right) {
        (Edge::Block, Edge::Block) if kind == BlockKind::Element => Some(block),
        (_, Edge::Br(run)) => Some(Span {
            start: line.start,
            end: run.end,
        }),
        (Edge::Br(run), Edge::Block) => Some(Span {
            start: run.start,
            end: line.end,
        }),
        _ => None,
    }
}

fn last_rule(events: &[Event<'_>]) -> Option<u32> {
    events.iter().rev().find_map(|event| match event {
        Event::Open { name, span, .. } if local_name(name).eq_ignore_ascii_case("hr") => {
            Some(span.start)
        }
        _ => None,
    })
}

fn title_of(events: &[Event<'_>]) -> (String, Option<Span>) {
    let mut title = String::new();
    let mut inner: Option<u32> = None;
    let mut tagged = false;
    for event in events {
        match event {
            Event::Open { name, .. } if local_name(name).eq_ignore_ascii_case("body") => break,
            Event::Open {
                name,
                span,
                self_closed: false,
                ..
            } if local_name(name).eq_ignore_ascii_case("title") => {
                inner = Some(span.end);
            }
            Event::Close { name, span } if local_name(name).eq_ignore_ascii_case("title") => {
                let span = inner.filter(|_| !tagged).map(|start| Span {
                    start,
                    end: span.start,
                });
                return (normalize(&title), span);
            }
            Event::Open { .. } | Event::Close { .. } if inner.is_some() => tagged = true,
            Event::Text { raw, .. } if inner.is_some() => title.push_str(&decode_text(raw)),
            _ => {}
        }
    }
    (normalize(&title), None)
}

impl Chapter {
    pub(crate) fn of(model: &ChapterModel, limits: &Limits) -> Result<Chapter, Error> {
        let scanned = scan(&model.source, limits)?;
        let events = &scanned.events;
        let (layout, ranges) = BlockLayout::build(events, &model.source);
        let visible = model.text.as_str();
        let mut paras = Vec::new();
        let mut push = |start: u32, end: u32, cut: Option<Span>, heading: bool| {
            let Some(vis) = model.text.visible_within(start, end) else {
                return;
            };
            let text = normalize(&visible[vis.start as usize..vis.end as usize]);
            if !text.is_empty() {
                paras.push(Para {
                    at: start,
                    vis,
                    cut,
                    heading,
                    text,
                });
            }
        };
        for (block, range) in layout.blocks.iter().zip(&ranges) {
            let all = &events[range.start as usize..range.end as usize];
            let inner = match (block.kind, all) {
                (BlockKind::Element, [Event::Open { name, .. }, ..]) if is_heading(name) => {
                    push(block.span.start, block.span.end, Some(block.span), true);
                    continue;
                }
                (BlockKind::Element, [_, inner @ .., _]) => inner,
                (BlockKind::Element, _) => &[],
                (BlockKind::BodyInner, _) => all,
            };
            let items = items(tokens(inner));
            for (ix, item) in items.iter().enumerate() {
                let Item::Line(line) = item else {
                    continue;
                };
                let edge = |at: Option<&Item>| match at {
                    Some(Item::Sep(edge)) => *edge,
                    _ => Edge::Block,
                };
                let left = edge(ix.checked_sub(1).and_then(|at| items.get(at)));
                let right = edge(items.get(ix + 1));
                let cut = line_cut(*line, left, right, block.span, block.kind)
                    .filter(|cut| balanced(all, *cut));
                push(line.start, line.end, cut, false);
            }
        }
        let (title, title_span) = title_of(events);
        Ok(Chapter {
            paras,
            title,
            title_span,
            last_rule: last_rule(events),
        })
    }
}

fn opens_with_quote(text: &str) -> bool {
    text.starts_with(['"', '“', '”', '「', '『'])
}

fn pattern_rule(para: &Para) -> Option<CleanRule> {
    if para.heading || opens_with_quote(&para.text) {
        return None;
    }
    let chars = para.text.chars().count();
    compiled()
        .iter()
        .find(|pattern| chars <= pattern.max_chars && pattern.regex.is_match(&para.text))
        .map(|pattern| pattern.rule)
}

fn title_key(text: &str) -> String {
    let mut folded = String::with_capacity(text.len());
    let mut previous = ' ';
    for ch in text.to_lowercase().chars() {
        if matches!(ch, '\'' | '‘' | '’' | 'ʼ') {
            continue;
        }
        let ch = if ch.is_alphanumeric() { ch } else { ' ' };
        if ch.is_numeric() != previous.is_numeric() && ch != ' ' && previous != ' ' {
            folded.push(' ');
        }
        folded.push(ch);
        previous = ch;
    }
    folded.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn truncated(full: &str, cut: &str) -> bool {
    !cut.is_empty() && full.starts_with(cut) && full.len() - cut.len() <= MAX_TITLE_TRUNCATION
}

fn numbered(key: &str) -> Option<(u64, String)> {
    let words: Vec<&str> = key.split(' ').collect();
    let at = words
        .iter()
        .position(|word| !word.chars().all(char::is_alphabetic))?;
    let number = words[at].parse::<u64>().ok()?;
    (at <= 4).then(|| (number, words[at + 1..].join(" ")))
}

fn repeats_title(candidate: &str, title: &str) -> bool {
    let (candidate, title) = (title_key(candidate), title_key(title));
    if candidate.is_empty() || title.is_empty() {
        return false;
    }
    if candidate == title {
        return true;
    }
    let (ours, theirs) = (numbered(&candidate), numbered(&title));
    if let (Some((ours, our_rest)), Some((theirs, their_rest))) = (&ours, &theirs)
        && ours == theirs
        && (our_rest == their_rest || our_rest.is_empty() || truncated(our_rest, their_rest))
    {
        return true;
    }
    theirs.is_some_and(|(_, rest)| !rest.is_empty() && rest == candidate)
}

const NOT_CHAPTERS: &[&str] = &[
    "volume", "vol", "book", "part", "arc", "act", "side", "season", "day", "week", "year", "page",
    "step", "level", "no", "num", "item", "unit", "case", "floor", "room", "bonus",
    "extra", "special",
];

pub(crate) struct ChapterTitle {
    pub(crate) number: u64,
    pub(crate) name: String,
}

fn title_pattern() -> &'static Regex {
    static PATTERN: OnceLock<Regex> = OnceLock::new();
    PATTERN.get_or_init(|| {
        Regex::new(
            r"^(?:(?:(\p{Lu}\p{L}{0,4})\s+)?((?i:chapter|chap|ch|episode|ep|c)|\p{Lu}{2,5})\.?\s*)?([0-9]{1,6})(.*)$",
        )
            .expect("the title pattern compiles")
    })
}

fn after_separator(rest: &str) -> Option<(&str, bool)> {
    let trimmed = rest.trim_start();
    let after = trimmed.trim_start_matches(|ch: char| {
        matches!(ch, ':' | '-' | '–' | '—' | '.') || ch.is_whitespace()
    });
    if after.len() < trimmed.len() {
        Some((after, true))
    } else if trimmed.len() < rest.len() || trimmed.is_empty() {
        Some((trimmed, false))
    } else {
        None
    }
}

pub(crate) fn chapter_title(text: &str) -> Option<ChapterTitle> {
    let visible: String = text
        .chars()
        .filter(|ch| !matches!(ch, '\u{200B}'..='\u{200D}' | '\u{2060}' | '\u{FEFF}'))
        .collect();
    let text = visible.split_whitespace().collect::<Vec<_>>().join(" ");
    let found = title_pattern().captures(&text)?;
    let refused = |word: &str| NOT_CHAPTERS.contains(&word.to_lowercase().as_str());
    if let Some(tag) = found.get(1) {
        let prefix = found.get(2)?.as_str();
        if refused(tag.as_str()) || prefix.chars().all(char::is_uppercase) && prefix.len() > 1 {
            return None;
        }
    }
    if found.get(2).is_some_and(|prefix| refused(prefix.as_str())) {
        return None;
    }
    let digits = found.get(3)?.as_str();
    let rest = found.get(4)?.as_str();
    let mut chars = rest.chars();
    let decimal = matches!(chars.next(), Some('.' | ','))
        && chars.next().is_some_and(|ch| ch.is_ascii_digit());
    if decimal || rest.starts_with(|ch: char| ch.is_ascii_digit()) {
        return None;
    }
    let (mut name, mut separated) = after_separator(rest)?;
    if let Some(again) = name.strip_prefix(digits)
        && !again.starts_with(|ch: char| ch.is_ascii_digit())
        && let Some((after, split)) = after_separator(again)
    {
        name = after;
        separated |= split;
    }
    if !separated && name.starts_with(char::is_lowercase) {
        return None;
    }
    let worded = |found: &regex::Captures<'_>| {
        found
            .get(2)
            .is_some_and(|prefix| !prefix.as_str().chars().all(char::is_uppercase))
    };
    if title_pattern()
        .captures(name)
        .is_some_and(|inner| worded(&inner))
    {
        return None;
    }
    Some(ChapterTitle {
        number: digits.parse().ok()?,
        name: name.trim_end().to_owned(),
    })
}

const MINOR_WORDS: &[&str] = &[
    "a", "an", "the", "and", "but", "or", "nor", "for", "as", "at", "by", "in", "of", "on", "per",
    "to", "via", "vs",
];

const APOSTROPHES: [char; 3] = ['\'', '\u{2019}', '\u{2018}'];

const DASHES: [char; 3] = ['-', '\u{2013}', '\u{2014}'];

fn ends_phrase(word: &str) -> bool {
    let word = word.trim_end_matches(['"', '\u{201D}', '\u{2019}', ')', ']']);
    word.chars().all(|ch| DASHES.contains(&ch))
        || word.ends_with([':', '?', '!', '\u{2013}', '\u{2014}'])
}

fn case_part(part: &str, capital: bool) -> String {
    if part.chars().any(char::is_numeric) {
        return part.to_owned();
    }
    let head = part.split(APOSTROPHES).next().unwrap_or_default();
    let mut letters = head.chars().filter(|ch| ch.is_alphabetic());
    if letters.clone().count() >= 2 && letters.all(char::is_uppercase) {
        return part.to_owned();
    }
    let core: String = part
        .chars()
        .filter(|ch| ch.is_alphabetic())
        .flat_map(char::to_lowercase)
        .collect();
    let minor = !capital && MINOR_WORDS.contains(&core.as_str());
    let mut seen = false;
    let mut after_apostrophe = false;
    let mut out = String::with_capacity(part.len());
    for ch in part.chars() {
        if ch.is_alphabetic() {
            if minor || seen && after_apostrophe {
                out.extend(ch.to_lowercase());
            } else if seen {
                out.push(ch);
            } else {
                out.extend(ch.to_uppercase());
            }
            seen = true;
            after_apostrophe = false;
        } else {
            out.push(ch);
            after_apostrophe = seen && APOSTROPHES.contains(&ch);
        }
    }
    out
}

pub(crate) fn title_case(name: &str) -> String {
    let words: Vec<&str> = name.split(' ').collect();
    let last = words
        .iter()
        .rposition(|word| word.chars().any(char::is_alphabetic));
    let mut start = true;
    let mut out = Vec::with_capacity(words.len());
    for (ix, word) in words.iter().enumerate() {
        let capital = start || Some(ix) == last || word.contains(DASHES);
        out.push(
            word.split_inclusive(DASHES)
                .map(|part| case_part(part, capital))
                .collect::<String>(),
        );
        start = ends_phrase(word) || start && !word.chars().any(char::is_alphabetic);
    }
    out.join(" ")
}

fn retitle(chapter: &Chapter, rules: &[Option<CleanRule>]) -> Option<Retitle> {
    let (heading, parsed) = chapter
        .paras
        .iter()
        .enumerate()
        .filter(|(_, para)| para.heading)
        .find_map(|(ix, para)| Some((ix, chapter_title(&para.text)?)))?;
    let text = &chapter.paras[heading].text;
    let (name, pulled) = if parsed.name.is_empty() {
        let next = heading + 1;
        let candidate = if chapter.paras.get(next).is_some_and(|para| para.heading) {
            next
        } else {
            (next..chapter.paras.len())
                .find(|&ix| !chapter.paras[ix].heading && rules[ix].is_none())?
        };
        let para = &chapter.paras[candidate];
        if para.cut.is_none()
            || opens_with_quote(&para.text)
            || para.text.chars().count() > MAX_PULLED_CHARS
        {
            return None;
        }
        let body = chapter_title(&para.text)?;
        if body.number != parsed.number || body.name.is_empty() {
            return None;
        }
        (body.name, Some(candidate))
    } else {
        (parsed.name, None)
    };
    let title = format!("{} {}", parsed.number, title_case(&name));
    (title != *text).then_some(Retitle {
        heading,
        pulled,
        title,
    })
}

fn repeated_heading(chapter: &Chapter, rules: &[Option<CleanRule>]) -> Option<usize> {
    let first = chapter.paras.iter().position(|para| para.heading)?;
    let heading = &chapter.paras[first].text;
    let candidate = (first + 1..chapter.paras.len())
        .find(|&ix| !chapter.paras[ix].heading && rules[ix].is_none())?;
    let text = &chapter.paras[candidate].text;
    (repeats_title(text, heading) || repeats_title(text, &chapter.title)).then_some(candidate)
}

fn note_tail(chapter: &Chapter, rules: &[Option<CleanRule>]) -> Vec<usize> {
    let Some(rule_at) = chapter.last_rule else {
        return Vec::new();
    };
    let first = chapter.paras.partition_point(|para| para.at < rule_at);
    if rules.get(first) != Some(&Some(CleanRule::Notes)) {
        return Vec::new();
    }
    let rest: Vec<usize> = (first + 1..chapter.paras.len())
        .filter(|&ix| rules[ix].is_none())
        .collect();
    let all_notes = rest.iter().all(|&ix| {
        let para = &chapter.paras[ix];
        !para.heading
            && !opens_with_quote(&para.text)
            && para.text.chars().count() <= MAX_NOTE_CHARS
    });
    if all_notes && rest.len() <= MAX_NOTE_TAIL {
        rest
    } else {
        Vec::new()
    }
}

pub(crate) fn find(chapter: &Chapter, enabled: &[CleanRule]) -> Vec<Change> {
    let mut rules: Vec<Option<CleanRule>> = chapter.paras.iter().map(pattern_rule).collect();
    for ix in note_tail(chapter, &rules) {
        rules[ix] = Some(CleanRule::Notes);
    }
    let retitled = retitle(chapter, &rules).filter(|_| enabled.contains(&CleanRule::Titles));
    if let Some(ix) = retitled.as_ref().and_then(|fix| fix.pulled) {
        rules[ix] = Some(CleanRule::Titles);
    }
    let heading = repeated_heading(chapter, &rules);
    let mut changes: Vec<Change> = chapter
        .paras
        .iter()
        .enumerate()
        .filter(|(_, para)| para.cut.is_some())
        .filter_map(|(ix, _)| {
            let rule = rules[ix].or((heading == Some(ix)).then_some(CleanRule::Heading))?;
            (rule != CleanRule::Titles && enabled.contains(&rule))
                .then_some(Change::Remove { rule, para: ix })
        })
        .collect();
    if let Some(fix) = retitled {
        let at = changes.partition_point(|change| change.para() < fix.heading);
        changes.insert(at, Change::Retitle(fix));
    }
    changes
}

fn without_space(text: &str) -> impl Iterator<Item = char> + '_ {
    text.chars().filter(|ch| !ch.is_whitespace())
}

fn tags<'a>(
    source: &'a str,
    events: &'a [Event<'a>],
    cuts: &'a [Span],
) -> impl Iterator<Item = &'a str> + 'a {
    events.iter().filter_map(move |event| match event {
        Event::Open { span, .. } | Event::Close { span, .. }
            if !cuts.iter().any(|cut| within(*span, *cut)) =>
        {
            Some(&source[span.range()])
        }
        _ => None,
    })
}

fn merged(mut cuts: Vec<Span>) -> Vec<Span> {
    cuts.sort_by_key(|cut| cut.start);
    let mut out: Vec<Span> = Vec::with_capacity(cuts.len());
    for cut in cuts {
        match out.last_mut() {
            Some(last) if cut.start <= last.end => last.end = last.end.max(cut.end),
            _ => out.push(cut),
        }
    }
    out
}

pub(crate) fn rewrite(
    model: &ChapterModel,
    chapter: &Chapter,
    changes: &[Change],
    limits: &Limits,
) -> Result<(Vec<u8>, Vec<String>), ()> {
    let mut gone: Vec<&Para> = Vec::new();
    let mut retitled: Option<&Retitle> = None;
    for change in changes {
        match change {
            Change::Remove { para, .. } => gone.push(&chapter.paras[*para]),
            Change::Retitle(fix) => {
                if retitled.replace(fix).is_some() {
                    return Err(());
                }
                gone.extend(fix.pulled.map(|ix| &chapter.paras[ix]));
            }
        }
    }
    let cuts = merged(gone.iter().filter_map(|para| para.cut).collect());
    let mut edits: Vec<SourceEdit> = cuts
        .iter()
        .map(|cut| SourceEdit {
            span: *cut,
            text: String::new(),
        })
        .collect();
    let mut swaps: Vec<(VisRange, &str)> = gone.iter().map(|para| (para.vis, "")).collect();
    if let Some(fix) = retitled {
        let heading = &chapter.paras[fix.heading];
        edits.extend(model.text.source_edits(heading.vis, &fix.title));
        swaps.push((heading.vis, &fix.title));
        if let Some(span) = chapter.title_span {
            edits.push(SourceEdit {
                span,
                text: escaped_title(&fix.title),
            });
        }
    }
    let (bytes, warnings) = finish_bytes(model, edits);
    let new = decode_and_model(bytes.clone(), limits).map_err(|_| ())?;
    let old = model.text.as_str();
    swaps.sort_by_key(|(range, _)| range.start);
    let mut expected = String::with_capacity(old.len());
    let mut cursor = 0;
    for (range, text) in swaps {
        let start = range.start as usize;
        if start < cursor {
            return Err(());
        }
        expected.push_str(&old[cursor..start]);
        expected.push_str(text);
        cursor = range.end as usize;
    }
    expected.push_str(&old[cursor..]);
    if !without_space(new.text.as_str()).eq(without_space(&expected)) {
        return Err(());
    }
    let old_scan = scan(&model.source, limits).map_err(|_| ())?;
    let new_scan = scan(&new.source, limits).map_err(|_| ())?;
    if let Some(fix) = retitled
        && chapter.title_span.is_some()
        && title_of(&new_scan.events).0 != fix.title
    {
        return Err(());
    }
    if tags(&model.source, &old_scan.events, &cuts).eq(tags(&new.source, &new_scan.events, &[])) {
        Ok((bytes, warnings))
    } else {
        Err(())
    }
}

fn escaped_title(title: &str) -> String {
    title
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

