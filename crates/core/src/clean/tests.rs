#[test]
fn a_second_heading_with_the_same_number_is_pulled_up_and_removed() {
    let body = "<h1>Chapter 41</h1><div><h2>Chapter 41: Dissecting Rocks</h2><p></p><p>Translator: Reedling</p></div><div><p>Story.</p></div>";
    let changes = retitled("", body, TITLES);
    assert_eq!(
        changes,
        vec![Change::Retitle(Retitle {
            heading: 0,
            pulled: Some(1),
            title: "41 Dissecting Rocks".to_owned(),
        })]
    );
    let after = rewritten("", body, TITLES);
    assert!(
        after
            .contains("<h1>41 Dissecting Rocks</h1><div><p></p><p>Translator: Reedling</p></div>"),
        "{after}"
    );
    let other = "<h1>Chapter 41</h1><h2>Chapter 42: Next One</h2><p>Story.</p>";
    assert_eq!(retitled("", other, TITLES), vec![]);
}

