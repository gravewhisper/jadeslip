fn retitled(title: &str, body: &str, enabled: &[CleanRule]) -> Vec<Change> {
    let model = titled(title, body);
    let chapter = Chapter::of(&model, &DEFAULT_LIMITS).unwrap();
    find(&chapter, enabled)
}

