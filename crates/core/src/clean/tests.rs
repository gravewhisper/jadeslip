const REPORT: &str = "If you find any errors ( broken links, non-standard content, etc.. ), Please let us know &lt; report chapter &gt; so we can fix it as soon as possible.";
const REPORT_ADS: &str = "If you find any errors ( Ads popup, ads redirect, broken links, non-standard content, etc.. ), Please let us know &lt; report chapter &gt; so we can fix it as soon as possible.";

#[test]
fn the_report_chapter_line_goes_in_every_shape_the_books_use() {
    let shapes = [
        format!("<p>Story.</p><p>{REPORT_ADS}</p>"),
        format!("<p>Story.</p><div align=\"left\">\n        {REPORT} </div>"),
        format!(
            "<div><div><p>Story.</p></div></div><p></p><div align=\"left\">\n        {REPORT} </div>"
        ),
        format!("<p>Story.</p><p><img src=\"../pixel.jpg\"/> {REPORT_ADS}</p>"),
    ];
    for body in shapes {
        let model = model(&body);
        let chapter = Chapter::of(&model, &DEFAULT_LIMITS).unwrap();
        let hits = pairs(find(&chapter, ALL));
        assert_eq!(hits.len(), 1, "{body}");
        assert_eq!(hits[0].0, CleanRule::Watermark, "{body}");
        let para = &chapter.paras[hits[0].1];
        let (bytes, _) = remove(&model, &[para], &DEFAULT_LIMITS).expect("removal verifies");
        let after = String::from_utf8(bytes).unwrap();
        assert!(!after.contains("report chapter"), "{after}");
        assert!(!after.contains("<img"), "{after}");
        assert!(after.contains("Story."), "{after}");
    }
}

