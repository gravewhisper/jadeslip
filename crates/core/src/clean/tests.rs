#[test]
fn br_lines_are_units_with_their_own_cuts() {
    let model = model("<div>\n  Chapter 9: X<br/><br/>Story.<br/>  <br/>Read at site.com</div>");
    let chapter = Chapter::of(&model, &DEFAULT_LIMITS).unwrap();
    let texts: Vec<&str> = chapter
        .paras
        .iter()
        .map(|para| para.text.as_str())
        .collect();
    assert_eq!(texts, ["Chapter 9: X", "Story.", "Read at site.com"]);
    let source = &model.source;
    let cut = |ix: usize| &source[chapter.paras[ix].cut.unwrap().range()];
    assert_eq!(cut(0), "Chapter 9: X<br/><br/>");
    assert_eq!(cut(1), "Story.<br/>  <br/>");
    assert_eq!(cut(2), "<br/>  <br/>Read at site.com");
    for para in &chapter.paras {
        assert_eq!(
            &model.text.as_str()[para.vis.start as usize..para.vis.end as usize],
            para.text
        );
    }
}

