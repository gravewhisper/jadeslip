#[test]
fn every_minor_word_stays_lower_case_between_two_words() {
    for word in [
        "a", "an", "the", "and", "but", "or", "nor", "for", "as", "at", "by", "in", "of", "on",
        "per", "to", "via", "vs",
    ] {
        let capital = format!("{}{}", word[..1].to_uppercase(), &word[1..]);
        assert_eq!(
            title_case(&format!("Sky {capital} Sea")),
            format!("Sky {word} Sea")
        );
        assert_eq!(title_case(&format!("{word} Sea")), format!("{capital} Sea"));
        assert_eq!(title_case(&format!("Sky {word}")), format!("Sky {capital}"));
    }
}

#[test]
fn a_named_heading_with_bad_case_is_a_title_fix_and_a_cased_one_is_not() {
    for (heading, title) in [
        (
            "28 Sacred Flame'S Flame Essence",
            "28 Sacred Flame's Flame Essence",
        ),
        ("Chapter 5: the sect of heaven", "5 The Sect of Heaven"),
    ] {
        let changes = retitled(heading, &format!("<h1>{heading}</h1><p>Story.</p>"), TITLES);
        assert_eq!(
            changes,
            vec![Change::Retitle(Retitle {
                heading: 0,
                pulled: None,
                title: title.to_owned(),
            })],
            "{heading}"
        );
    }
    for heading in ["28 Sacred Flame's Flame Essence", "28 sacred flame essence"] {
        assert_eq!(
            retitled(heading, &format!("<h1>{heading}</h1><p>Story.</p>"), TITLES),
            vec![],
            "{heading}"
        );
    }
}
