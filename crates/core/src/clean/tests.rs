#[test]
fn a_repeated_title_matches_only_as_the_first_unit_under_a_real_heading() {
    let heading = |h1: &str, first: &str| {
        found(&format!(
            "<h1>{h1}</h1><p>{first}</p><p>The story goes on.</p>"
        ))
    };
    let hit =
        |h1: &str, first: &str| heading(h1, first) == vec![(CleanRule::Heading, first.to_owned())];
    assert!(hit("Chapter 1483: Frost Gate", "Chapter 1483: Frost Gate"));
    assert!(hit("Chapter 12 – The Duel", "chapter 12 - the duel"));
    assert!(hit(
        "Chapter 236 – Silver Lanterns, Moths On The Quiet River Bank!",
        "IMC 236 – Silver Lanterns, Moths on the quiet river bank!"
    ));
    assert!(hit("Chapter 12: The Duel", "Chapter 12"));
    assert!(hit("Chapter 12: The Duel", "The Duel"));
    assert!(!hit("Chapter 12: The Duel", "Chapter 13"));
    assert!(!hit("Chapter 12: The Duel", "Chapter 12: The Feast"));
    assert!(!hit("Chapter 12: The Duel", "The duel began at dawn."));
    assert_eq!(
        found("<p>Chapter 12: The Duel</p><p>The story goes on.</p>"),
        vec![]
    );
    assert_eq!(
        found("<h1>Chapter 12</h1><p>Story.</p><p>Chapter 12</p>"),
        vec![]
    );
    assert_eq!(
        found(
            "<h1>Chapter 12: The Duel</h1><p>TL: Greywind</p><p>Chapter 12: The Duel</p><p>Story.</p>"
        ),
        vec![
            (CleanRule::Notes, "TL: Greywind".to_owned()),
            (CleanRule::Heading, "Chapter 12: The Duel".to_owned())
        ]
    );
}

