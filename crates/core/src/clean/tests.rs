use super::*;
use crate::DEFAULT_LIMITS;
use crate::chapter::{SourceEncoding, model_of_source};

fn model(body: &str) -> ChapterModel {
    model_of_source(
        format!(
            "<?xml version=\"1.0\"?><html xmlns=\"http://www.w3.org/1999/xhtml\"><head><title>T</title></head><body>{body}</body></html>"
        ),
        SourceEncoding::Utf8 { bom: false },
        &DEFAULT_LIMITS,
    )
    .unwrap()
}

fn remove(
    model: &ChapterModel,
    paras: &[&Para],
    limits: &Limits,
) -> Result<(Vec<u8>, Vec<String>), ()> {
    let chapter = Chapter::of(model, limits).unwrap();
    let changes: Vec<Change> = paras
        .iter()
        .map(|wanted| Change::Remove {
            rule: CleanRule::Watermark,
            para: chapter
                .paras
                .iter()
                .position(|para| para.vis == wanted.vis)
                .unwrap(),
        })
        .collect();
    rewrite(model, &chapter, &changes, limits)
}

fn pairs(changes: Vec<Change>) -> Vec<(CleanRule, usize)> {
    changes
        .iter()
        .map(|change| (change.rule(), change.para()))
        .collect()
}

#[test]
fn two_matching_br_lines_at_the_end_of_a_div_both_go() {
    let model = model("<div>Story line.<br/><br/>Read at novelsite.com<br/>TL: Someone</div>");
    let chapter = Chapter::of(&model, &DEFAULT_LIMITS).unwrap();
    let units: Vec<&Para> = chapter.paras.iter().skip(1).collect();
    assert_eq!(units.len(), 2);
    let (bytes, _) = remove(&model, &units, &DEFAULT_LIMITS).unwrap();
    let after = String::from_utf8(bytes).unwrap();
    assert!(
        after.contains("<div>Story line.<br/><br/></div>"),
        "{after}"
    );
}

const ALL: &[CleanRule] = &[CleanRule::Watermark, CleanRule::Notes, CleanRule::Heading];

fn found(body: &str) -> Vec<(CleanRule, String)> {
    let model = model(body);
    let chapter = Chapter::of(&model, &DEFAULT_LIMITS).unwrap();
    pairs(find(&chapter, ALL))
        .into_iter()
        .map(|(rule, ix)| (rule, chapter.paras[ix].text.clone()))
        .collect()
}

fn rule_of(line: &str) -> Option<CleanRule> {
    let hits = found(&format!(
        "<p>Story first.</p><p>{line}</p><p>Story last.</p>"
    ));
    assert!(hits.len() <= 1, "{hits:?}");
    hits.first().map(|(rule, _)| *rule)
}

