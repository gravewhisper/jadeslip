fn rewritten(title: &str, body: &str, enabled: &[CleanRule]) -> String {
    let model = titled(title, body);
    let chapter = Chapter::of(&model, &DEFAULT_LIMITS).unwrap();
    let changes = find(&chapter, enabled);
    let (bytes, _) =
        rewrite(&model, &chapter, &changes, &DEFAULT_LIMITS).expect("the rewrite verifies");
    String::from_utf8(bytes).unwrap()
}

